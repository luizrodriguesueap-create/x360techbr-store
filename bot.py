def btn(t, cb=None, u=None, s="primary"):
    k = {"text": t}
    if cb:
        k["callback_data"] = cb
    if u:
        k["url"] = u
    try:
        return IKB(**k, style=s)
    except:
        return IKB(**k)

def slugify(text: str) -> str:
    cleaned = re.sub(r'[^a-zA-Z0-9]+', '_', text.strip().lower()).strip('_')
    return cleaned[:25] or "jogo"

